#!/usr/bin/env node
/**
 * Contract ABI Exporter (T08)
 * Specification §7, §8 (R05, R06, R10)
 * 
 * Exports authoritative compiled ABIs from Hardhat artifacts to frontend/src/contracts/generated/
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const ROOT_DIR = path.resolve(__dirname, '..')
const ARTIFACTS_DIR = path.join(ROOT_DIR, 'artifacts', 'contracts')
const TARGET_DIR = path.join(ROOT_DIR, 'frontend', 'src', 'contracts', 'generated')

const CONTRACTS_MAP = {
  AuditEngine: path.join(ARTIFACTS_DIR, 'AuditEngine.sol', 'AuditEngine.json'),
  ComplianceRules: path.join(ARTIFACTS_DIR, 'ComplianceRules.sol', 'ComplianceRules.json'),
  MultiSigApproval: path.join(ARTIFACTS_DIR, 'access', 'MultiSigApproval.sol', 'MultiSigApproval.json'),
  RoleManager: path.join(ARTIFACTS_DIR, 'access', 'RoleManager.sol', 'RoleManager.json'),
  ForensicTrail: path.join(ARTIFACTS_DIR, 'forensics', 'ForensicTrail.sol', 'ForensicTrail.json'),
  InsiderActivityLog: path.join(ARTIFACTS_DIR, 'forensics', 'InsiderActivityLog.sol', 'InsiderActivityLog.json'),
}

export function exportContracts() {
  if (!fs.existsSync(TARGET_DIR)) {
    fs.mkdirSync(TARGET_DIR, { recursive: true })
  }

  const exportIndexLines = [
    '/**',
    ' * Authoritative Generated Contract ABIs (T08)',
    ' * Auto-generated by scripts/export-contracts.js from Hardhat artifacts.',
    ' * DO NOT EDIT MANUALLY.',
    ' */',
    '',
  ]

  for (const [name, artifactPath] of Object.entries(CONTRACTS_MAP)) {
    if (!fs.existsSync(artifactPath)) {
      throw new Error(`Artifact for ${name} not found at ${artifactPath}. Please run 'npx hardhat compile' first.`)
    }

    const artifactContent = JSON.parse(fs.readFileSync(artifactPath, 'utf-8'))
    const abi = artifactContent.abi

    const targetJsonPath = path.join(TARGET_DIR, `${name}.json`)
    fs.writeFileSync(targetJsonPath, JSON.stringify(abi, null, 2) + '\n', 'utf-8')

    // Also write a js wrapper for easy import without assert { type: 'json' }
    const targetJsPath = path.join(TARGET_DIR, `${name}.js`)
    fs.writeFileSync(targetJsPath, `export default ${JSON.stringify(abi, null, 2)}\n`, 'utf-8')

    exportIndexLines.push(`import ${name}ABI from './${name}.js'`)
    exportIndexLines.push(`export { ${name}ABI }`)
  }

  exportIndexLines.push('')
  exportIndexLines.push('export const CONTRACT_ABIS = {')
  for (const name of Object.keys(CONTRACTS_MAP)) {
    exportIndexLines.push(`  ${name}: ${name}ABI,`)
  }
  exportIndexLines.push('}')
  exportIndexLines.push('')

  fs.writeFileSync(path.join(TARGET_DIR, 'index.js'), exportIndexLines.join('\n'), 'utf-8')
  console.log(`[SUCCESS] Exported 6 contract ABIs to ${TARGET_DIR}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  exportContracts()
}
